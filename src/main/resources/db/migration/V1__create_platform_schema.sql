CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL
);

CREATE TABLE companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(1000),
    location VARCHAR(255),
    website VARCHAR(255)
);

CREATE TABLE jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description VARCHAR(4000) NOT NULL,
    location VARCHAR(255) NOT NULL,
    employment_type VARCHAR(255) NOT NULL,
    min_experience INTEGER,
    salary_range VARCHAR(255),
    salary_sort_value DOUBLE PRECISION,
    created_at TIMESTAMP NOT NULL,
    status VARCHAR(255) NOT NULL,
    company_id BIGINT NOT NULL,
    posted_by BIGINT NOT NULL,
    CONSTRAINT fk_jobs_company FOREIGN KEY (company_id) REFERENCES companies (id),
    CONSTRAINT fk_jobs_user FOREIGN KEY (posted_by) REFERENCES users (id)
);

CREATE TABLE job_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id BIGINT NOT NULL,
    candidate_id BIGINT NOT NULL,
    resume_url VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    applied_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_applications_job FOREIGN KEY (job_id) REFERENCES jobs (id),
    CONSTRAINT fk_applications_candidate FOREIGN KEY (candidate_id) REFERENCES users (id)
);

CREATE INDEX idx_jobs_created_at ON jobs (created_at DESC, id DESC);
CREATE INDEX idx_jobs_min_experience ON jobs (min_experience);
CREATE INDEX idx_jobs_salary_sort_value ON jobs (salary_sort_value DESC);
CREATE INDEX idx_jobs_posted_by ON jobs (posted_by);
CREATE INDEX idx_jobs_company_id ON jobs (company_id);
CREATE INDEX idx_applications_candidate_applied ON job_applications (candidate_id, applied_at DESC);
CREATE INDEX idx_applications_job_applied ON job_applications (job_id, applied_at DESC);
